#!/usr/bin/env python3
"""Adversarial persistence checks for issue #466 (Fire TV Audio Boost).

The issue requires the selected boost to survive sessions and app restarts, and
the store has no other executable coverage. This suite compiles the real
AndroidAudioBoostStore.kt, unmodified, against minimal android.content stand-ins
(Issue466AndroidContextStub.kt) and runs the driver in
Issue466AudioBoostPersistenceDriver.kt. It covers:

- relaunch round trips for every offered level, plus the last-write-wins order;
- fresh install, unoffered writes, and corrupt stored values all reading as Off;
- preference isolation (dedicated file, application context).

Needs only java and the Kotlin compiler jars already in the Gradle cache (the
same toolchain as the issue #466 contract suite); no device or network access.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "clients/tv-android/app/src/main/kotlin/app/swarm/tv/app"
STORE = APP / "data/AndroidAudioBoostStore.kt"
HERE = Path(__file__).parent
STUB = HERE / "Issue466AndroidContextStub.kt"
DRIVER = HERE / "Issue466AudioBoostPersistenceDriver.kt"
MAIN_CLASS = "Issue466AudioBoostPersistenceDriverKt"


def fail(message: str) -> None:
    print(f"FAIL: {message}", file=sys.stderr)
    sys.stderr.flush()
    sys.exit(1)


def version_key(path: Path) -> tuple[int, ...]:
    return tuple(int(part) for part in re.findall(r"\d+", path.stem.split("-")[-1]))


def newest_jar(artifact_pattern: str) -> str:
    cache = Path.home() / ".gradle/caches/modules-2/files-2.1"
    candidates = [
        p
        for p in cache.glob(f"**/{artifact_pattern}")
        if "sources" not in p.name and "javadoc" not in p.name
    ]
    if not candidates:
        fail(f"{artifact_pattern} is absent from the Gradle cache")
    return str(max(candidates, key=version_key))


def kotlin_compiler_command() -> list[str]:
    compiler = newest_jar("kotlin-compiler-embeddable-*.jar")
    extras = [
        newest_jar("kotlin-stdlib-[0-9]*.jar"),
        newest_jar("kotlin-script-runtime-*.jar"),
        newest_jar("kotlin-reflect-*.jar"),
        newest_jar("kotlin-daemon-embeddable-*.jar"),
        newest_jar("kotlinx-coroutines-core-jvm-*.jar"),
        newest_jar("org.jetbrains/annotations/*/*/annotations-*.jar"),
        newest_jar("trove4j-*.jar"),
    ]
    return [
        "java",
        "-cp",
        ":".join([compiler, *extras]),
        "org.jetbrains.kotlin.cli.jvm.K2JVMCompiler",
    ]


def main() -> None:
    # Generated bytecode references org.jetbrains.annotations, needed at compile and run time.
    stdlib = ":".join([newest_jar("kotlin-stdlib-[0-9]*.jar"), newest_jar("org.jetbrains/annotations/*/*/annotations-*.jar")])
    with tempfile.TemporaryDirectory() as temp:
        out = Path(temp) / "classes"
        out.mkdir()
        compile_result = subprocess.run(
            kotlin_compiler_command()
            + [
                "-no-stdlib",
                "-no-reflect",
                "-cp",
                stdlib,
                "-d",
                str(out),
                str(STORE),
                str(STUB),
                str(DRIVER),
            ],
            capture_output=True,
            text=True,
        )
        if compile_result.returncode:
            fail(
                "persistence driver compilation failed:\n"
                f"{compile_result.stdout}\n{compile_result.stderr}"
            )
        run_result = subprocess.run(
            ["java", "-cp", f"{out}:{stdlib}", MAIN_CLASS],
            capture_output=True,
            text=True,
        )
        if run_result.returncode or "ALL_OK" not in run_result.stdout:
            fail(
                "audio boost persistence contract failed:\n"
                f"{run_result.stdout}\n{run_result.stderr}"
            )
    print("PASS: Issue #466 audio boost persistence adversarial checks")


if __name__ == "__main__":
    main()
